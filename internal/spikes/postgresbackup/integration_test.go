const postgresImage = "postgres:18.6-alpine3.23@sha256:8c80c49c67052d82f9aaf4ee1f1881c8926b445a1cc916892934845eb8c24204"

var fixtureTools Tools

func TestMain(m *testing.M) {
	if os.Getenv("PRIVATE_REGISTRY_PG_TOOL_HELPER") != "" {
		os.Exit(m.Run())
	}
	os.Exit(runIntegration(m))
}

func runIntegration(m *testing.M) (exitCode int) {
	var suffix [16]byte
	if _, err := rand.Read(suffix[:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	name := "private-registry-postgres-" + hex.EncodeToString(suffix[:])
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()
	output, err := exec.CommandContext(ctx, "docker", "run", "--detach", "--pull=never", "--name", name,
		"--network=none", "--cpus=2", "--memory=512m", "--pids-limit=256", "--security-opt=no-new-privileges",
		"--env", "POSTGRES_HOST_AUTH_METHOD=trust", postgresImage).CombinedOutput()
	if err != nil {
		fmt.Fprintf(os.Stderr, "start isolated PostgreSQL (run make setup-postgres): %v\n%s", err, output)
		return 1
	}
	defer func() {
		cleanup, stop := context.WithTimeout(context.Background(), 60*time.Second)
		defer stop()
		if output, err := exec.CommandContext(cleanup, "docker", "rm", "--force", "--volumes", name).CombinedOutput(); err != nil {
			fmt.Fprintf(os.Stderr, "cleanup owned PostgreSQL container: %v\n%s", err, output)
			exitCode = 1
		}
	}()
	fixtureTools = Tools{Executable: "docker", Prefix: []string{"exec", "--interactive", name}, ExpectedMajor: 18}
	for {
		// The image's temporary initialization server accepts Unix sockets but
		// no TCP. Probe TCP to avoid mistaking that server for the final one.
		if output, err := fixtureTools.command(ctx, "psql", "--host=127.0.0.1", "--username=postgres", "--no-password", "--tuples-only", "--no-align", "--command=SELECT 1").CombinedOutput(); err == nil && strings.TrimSpace(string(output)) == "1" {
			break
		}
		select {
		case <-ctx.Done():
			fmt.Fprintln(os.Stderr, "isolated PostgreSQL did not become ready")
			return 1
		case <-time.After(50 * time.Millisecond):
		}
	}
	exitCode = m.Run()
	if exitCode != 0 {
		// Preserve evidence before owned-container cleanup. Do not retry failed
		// database operations: a server failure may have unknown commit state.
		diagnostics, stop := context.WithTimeout(context.Background(), 10*time.Second)
		defer stop()
		state, _ := exec.CommandContext(diagnostics, "docker", "inspect", "--format", "{{json .State}}", name).CombinedOutput()
		logs, _ := exec.CommandContext(diagnostics, "docker", "logs", "--tail", "80", name).CombinedOutput()
		fmt.Fprintf(os.Stderr, "owned PostgreSQL failure state: %s\nserver log tail:\n%s\n", state, logs)
	}
	return exitCode
}

func database(t *testing.T, ctx context.Context) string {
	t.Helper()
	var suffix [12]byte
	if _, err := rand.Read(suffix[:]); err != nil {
		t.Fatal(err)
	}
	name := "spike_" + hex.EncodeToString(suffix[:])
	if err := run(fixtureTools.command(ctx, "createdb", "--username=postgres", "--no-password", name), io.Discard, nil); err != nil {
		t.Fatal(err)
	}
	return name
}

func query(t *testing.T, ctx context.Context, database, sql string) string {
	t.Helper()
	var output bytes.Buffer
	err := run(fixtureTools.command(ctx, "psql", "--username=postgres", "--no-password", "--quiet", "--tuples-only", "--no-align", "--set=ON_ERROR_STOP=1", "--dbname="+database), &output, strings.NewReader(sql))
	if err != nil {
		t.Fatal(err)
	}
	return strings.TrimSpace(output.String())
}

func recoveryIdentity(t *testing.T) *age.X25519Identity {
	t.Helper()
	identity, err := age.GenerateX25519Identity()
	if err != nil {
		t.Fatal(err)
	}
	return identity
}

func operation(t *testing.T) context.Context {
	t.Helper()
	// Bound operations while accommodating a shared, occasionally busy daemon.
	ctx, cancel := context.WithTimeout(context.Background(), 90*time.Second)
	t.Cleanup(cancel)
	return ctx
}

func TestPostgresConsistentEncryptedRecoveryWithoutOrigin(t *testing.T) {
	ctx := operation(t)
	source := database(t, ctx)
	query(t, ctx, source, `CREATE TABLE owners(id bigint PRIMARY KEY, generation integer NOT NULL);
		CREATE TABLE packages(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id bigint NOT NULL REFERENCES owners(id), generation integer NOT NULL, payload bytea NOT NULL);
		INSERT INTO owners VALUES(1,1);
		INSERT INTO packages(owner_id,generation,payload) SELECT 1,1,decode(repeat(md5(n::text),128),'hex') FROM generate_series(1,128) n;`)
	version := query(t, ctx, source, "SHOW server_version;")
	if !strings.HasPrefix(version, "18.") {
		t.Fatalf("unexpected server version: %s", version)
	}
	if err := fixtureTools.CheckVersions(ctx); err != nil {
		t.Fatal(err)
	}
	// Hold a read-only exported MVCC snapshot while another connection commits.
	exporter := fixtureTools.command(ctx, "psql", "--username=postgres", "--no-password", "--quiet", "--tuples-only", "--no-align", "--set=ON_ERROR_STOP=1", "--dbname="+source)
	stdin, err := exporter.StdinPipe()
	if err != nil {
		t.Fatal(err)
	}
	stdout, err := exporter.StdoutPipe()
	if err != nil {
		t.Fatal(err)
	}
	var diagnostics cappedBuffer
	exporter.Stderr = &diagnostics
	if err := exporter.Start(); err != nil {
		t.Fatal(err)
	}
	waited := false
	defer func() {
		_ = stdin.Close()
		if !waited {
			_ = exporter.Wait()
		}
	}()
	if _, err := io.WriteString(stdin, "BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY; SELECT pg_export_snapshot();\n"); err != nil {
		t.Fatal(err)
	}
	scanner := bufio.NewScanner(stdout)
	if !scanner.Scan() {
		t.Fatalf("export snapshot: %v", scanner.Err())
	}
	snapshot := strings.TrimSpace(scanner.Text())
	if !snapshotName.MatchString(snapshot) {
		t.Fatalf("invalid exported snapshot: %s", snapshot)
	}
	query(t, ctx, source, `BEGIN; UPDATE owners SET generation=2; UPDATE packages SET generation=2;
		INSERT INTO packages(owner_id,generation,payload) VALUES(1,2,decode('ff','hex')); COMMIT;`)
	if actual := query(t, ctx, source, "SELECT count(*)||':'||min(generation) FROM packages;"); actual != "129:2" {
		t.Fatalf("concurrent writer did not commit: %s", actual)
	}
	identity := recoveryIdentity(t)
	sealed := filepath.Join(t.TempDir(), "backup.age")
	receipt, err := Dump(ctx, fixtureTools, source, snapshot, sealed, identity.Recipient(), 32<<20)
	if err != nil {
		t.Fatal(err)
	}
	if receipt.PlaintextBytes <= 0 || receipt.ToolsMajor != 18 || len(receipt.PlaintextSHA256) != 64 {
		t.Fatalf("invalid receipt: %+v", receipt)
	}
	if _, err := io.WriteString(stdin, "COMMIT;\n"); err != nil {
		t.Fatal(err)
	}
	if err := stdin.Close(); err != nil {
		t.Fatal(err)
	}
	exporterErr := exporter.Wait()
	waited = true
	if err := exporterErr; err != nil || diagnostics.total != 0 {
		t.Fatalf("snapshot exporter failed: %v %s", err, diagnostics.String())
	}
	// Remove the actual source before creating the recovery database.
	if err := run(fixtureTools.command(ctx, "dropdb", "--username=postgres", "--no-password", source), io.Discard, nil); err != nil {
		t.Fatal(err)
	}
	target := database(t, ctx)
	stage := t.TempDir()
	if err := Restore(ctx, fixtureTools, target, sealed, identity, receipt.PlaintextSHA256, receipt.PlaintextBytes, stage); err != nil {
		t.Fatal(err)
	}
	if actual := query(t, ctx, target, "SELECT count(*)||':'||min(generation)||':'||max(generation)||':'||sum(octet_length(payload)) FROM packages;"); actual != "128:1:1:262144" {
		t.Fatalf("restore did not match exported snapshot: %s", actual)
	}
	if actual := query(t, ctx, target, "SELECT generation FROM owners WHERE id=1;"); actual != "1" {
		t.Fatalf("related table snapshot inconsistent: %s", actual)
	}
	if actual := query(t, ctx, target, "SELECT count(*) FROM packages WHERE owner_id<>1 OR payload<>decode(repeat(md5(id::text),128),'hex');"); actual != "0" {
		t.Fatalf("restored payload bytes or owner references differ: %s", actual)
	}
	if actual := query(t, ctx, target, "SELECT count(*) FROM pg_constraint WHERE contype='f' AND conrelid='packages'::regclass;"); actual != "1" {
		t.Fatalf("foreign key missing: %s", actual)
	}
	if err := run(fixtureTools.command(ctx, "psql", "--username=postgres", "--no-password", "--set=ON_ERROR_STOP=1", "--dbname="+target,
		"--command=INSERT INTO packages(id,owner_id,generation,payload) VALUES(999,999,1,decode('aa','hex'));"), io.Discard, nil); err == nil || !strings.Contains(err.Error(), "foreign key constraint") {
		t.Fatalf("restored foreign key did not reject invalid reference: %v", err)
	}
	// Sequences are not MVCC state. The concurrent insert advanced the source
	// sequence to 129; the dump retains that safe high-water mark, not 128.
	if actual := query(t, ctx, target, "INSERT INTO packages(owner_id,generation,payload) VALUES(1,1,decode('aa','hex')) RETURNING id;"); actual != "130" {
		t.Fatalf("identity sequence not restored: %s", actual)
	}
	assertNoStage(t, stage)
	info, err := os.Stat(sealed)
	if err != nil || info.Mode().Perm() != 0o600 {
		t.Fatalf("ciphertext permissions: %v", err)
	}
	t.Logf("server %s, tools major %d: %d dump bytes; 128 original rows/262144 payload bytes restored after origin dropped; writer committed 129 rows/generation 2; snapshot generation 1 retained", version, receipt.ToolsMajor, receipt.PlaintextBytes)
}

func TestPostgresCancellationDuringLockWait(t *testing.T) {
	ctx := operation(t)
	source := database(t, ctx)
	query(t, ctx, source, "CREATE TABLE marker(id integer PRIMARY KEY); INSERT INTO marker VALUES(1);")
	holder := fixtureTools.command(ctx, "psql", "--username=postgres", "--no-password", "--quiet", "--tuples-only", "--no-align", "--set=ON_ERROR_STOP=1", "--dbname="+source)
	stdin, err := holder.StdinPipe()
	if err != nil {
		t.Fatal(err)
	}
	stdout, err := holder.StdoutPipe()
	if err != nil {
		t.Fatal(err)
	}
	var diagnostic cappedBuffer
	holder.Stderr = &diagnostic
	if err := holder.Start(); err != nil {
		t.Fatal(err)
	}
	defer func() { _ = stdin.Close(); _ = holder.Wait() }()
	if _, err := io.WriteString(stdin, "BEGIN; LOCK TABLE marker IN ACCESS EXCLUSIVE MODE; SELECT 'locked';\n"); err != nil {
		t.Fatal(err)
	}
	scanner := bufio.NewScanner(stdout)
	if !scanner.Scan() || scanner.Text() != "locked" {
		t.Fatalf("exclusive lock not acquired: %v", scanner.Err())
	}
	operation, cancel := context.WithTimeout(ctx, 60*time.Second)
	defer cancel()
	destination := filepath.Join(t.TempDir(), "canceled.age")
	identity := recoveryIdentity(t)
	done := make(chan error, 1)
	go func() {
		_, err := Dump(operation, fixtureTools, source, "", destination, identity.Recipient(), 8<<20)
		done <- err
	}()
	locked := false
	for !locked && operation.Err() == nil {
		locked = query(t, ctx, source, "SELECT count(*) FROM pg_stat_activity WHERE datname=current_database() AND application_name='pg_dump' AND wait_event_type='Lock';") == "1"
		if !locked {
			time.Sleep(20 * time.Millisecond)
		}
	}
	cancel()
	dumpErr := <-done
	if !locked {
		t.Fatalf("dump never reached the observed PostgreSQL lock wait: %v", dumpErr)
	}
	if !errors.Is(dumpErr, context.Canceled) {
		t.Fatalf("in-progress dump cancellation lost: %v", dumpErr)
	}
	if _, err := os.Stat(destination); !errors.Is(err, os.ErrNotExist) {
		t.Fatal("canceled lock-wait dump retained ciphertext")
	}
}

func assertNoStage(t *testing.T, directory string) {
	t.Helper()
	entries, err := os.ReadDir(directory)
	if err != nil || len(entries) != 0 {
		t.Fatalf("partial plaintext retained: %v %v", entries, err)
	}
}

func TestPostgresRecoveryRejectsInvalidArchivesBeforeMutation(t *testing.T) {
	ctx := operation(t)
	source := database(t, ctx)
	query(t, ctx, source, "CREATE TABLE alpha(id integer PRIMARY KEY); INSERT INTO alpha VALUES(7); CREATE TABLE marker(id integer PRIMARY KEY); INSERT INTO marker VALUES(1);")
	identity := recoveryIdentity(t)
	sealed := filepath.Join(t.TempDir(), "backup.age")
	receipt, err := Dump(ctx, fixtureTools, source, "", sealed, identity.Recipient(), 8<<20)
	if err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(sealed)
	if err != nil {
		t.Fatal(err)
	}
	for _, kind := range []string{"wrong_key", "tamper", "truncate", "digest", "limit", "missing", "canceled", "non_archive", "nonempty_target", "version"} {
		t.Run(kind, func(t *testing.T) {
			ctx := operation(t)
			target := database(t, ctx)
			file, key, digest, limit, tools := sealed, age.Identity(identity), receipt.PlaintextSHA256, receipt.PlaintextBytes, fixtureTools
			operation, cancel := context.WithCancel(ctx)
			defer cancel()
			switch kind {
			case "wrong_key":
				key = recoveryIdentity(t)
			case "tamper", "truncate":
				copy := bytes.Clone(data)
				if kind == "tamper" {
					copy[len(copy)-1] ^= 1
				} else {
					copy = copy[:len(copy)-16]
				}
				file = filepath.Join(t.TempDir(), "bad.age")
				if err := os.WriteFile(file, copy, 0o600); err != nil {
					t.Fatal(err)
				}
			case "digest":
				digest = strings.Repeat("0", 64)
			case "limit":
				limit--
			case "missing":
				file = filepath.Join(t.TempDir(), "missing")
			case "canceled":
				cancel()
			case "non_archive":
				file = filepath.Join(t.TempDir(), "not-dump.age")
				output, err := os.Create(file)
				if err != nil {
					t.Fatal(err)
				}
				writer, err := age.Encrypt(output, identity.Recipient())
				if err != nil {
					t.Fatal(err)
				}
				payload := []byte("not a PostgreSQL archive")
				_, err = writer.Write(payload)
				if err := errors.Join(err, writer.Close(), output.Close()); err != nil {
					t.Fatal(err)
				}
				hash := sha256.Sum256(payload)
				digest, limit = hex.EncodeToString(hash[:]), int64(len(payload))
			case "nonempty_target":
				query(t, ctx, target, "CREATE TABLE marker(id integer PRIMARY KEY); INSERT INTO marker VALUES(42);")
			case "version":
				tools.ExpectedMajor = 17
			}
			stage := t.TempDir()
			if err := Restore(operation, tools, target, file, key, digest, limit, stage); err == nil {
				t.Fatal("invalid recovery accepted")
			}
			assertNoStage(t, stage)
			if kind == "nonempty_target" {
				if actual := query(t, ctx, target, "SELECT id FROM marker;"); actual != "42" {
					t.Fatalf("existing target modified: %s", actual)
				}
				if actual := query(t, ctx, target, "SELECT count(*) FROM pg_tables WHERE schemaname='public';"); actual != "1" {
					t.Fatalf("failed restore did not roll back earlier DDL: %s", actual)
				}
			} else if actual := query(t, ctx, target, "SELECT count(*) FROM pg_tables WHERE schemaname='public';"); actual != "0" {
				t.Fatalf("invalid recovery mutated empty database: %s", actual)
			}
		})
	}
}

func TestPostgresDumpFailureRemovesPartialCiphertext(t *testing.T) {
	ctx := operation(t)
	source := database(t, ctx)
	query(t, ctx, source, "CREATE TABLE marker(id integer PRIMARY KEY); INSERT INTO marker VALUES(1);")
	identity := recoveryIdentity(t)
	for _, kind := range []string{"missing_database", "limit", "invalid_snapshot", "canceled", "existing", "version"} {
		t.Run(kind, func(t *testing.T) {
			operation, cancel := context.WithCancel(ctx)
			defer cancel()
			database, snapshot, limit, tools := source, "", int64(8<<20), fixtureTools
			destination := filepath.Join(t.TempDir(), "backup.age")
			switch kind {
			case "missing_database":
				database = "missing_fixture"
			case "limit":
				limit = 1
			case "invalid_snapshot":
				snapshot = "00000001-00000001-1"
			case "canceled":
				cancel()
			case "existing":
				if err := os.WriteFile(destination, []byte("keep"), 0o600); err != nil {
					t.Fatal(err)
				}
			case "version":
				tools.ExpectedMajor = 17
			}
			if _, err := Dump(operation, tools, database, snapshot, destination, identity.Recipient(), limit); err == nil {
				t.Fatal("invalid dump accepted")
			}
			if kind == "existing" {
				data, err := os.ReadFile(destination)
				if err != nil || string(data) != "keep" {
					t.Fatal("existing ciphertext overwritten")
				}
			} else if _, err := os.Stat(destination); !errors.Is(err, os.ErrNotExist) {
				t.Fatal("partial ciphertext retained")
			}
		})
	}
}
